function ev(taskId: string, kind: TaskEventKind, at: number, payload: Record<string, unknown> = {}, runId?: string): TaskEvent {
  return { id: nextEventId(), taskId, kind, at, payload, runId: runId ?? null };
}

type TaskSeed = Omit<KanbanTask, 'board' | 'comments' | 'events' | 'runs' | 'updatedAt'> &
  Partial<Pick<KanbanTask, 'board' | 'comments' | 'events' | 'runs' | 'updatedAt'>>;

function task(t: TaskSeed): KanbanTask {
  const events = t.events ?? [ev(t.id, 'created', t.createdAt, { assignee: t.assignee, status: t.status, parents: t.parents })];
  return {
    board: 'default',
    comments: [],
    runs: [],
    updatedAt: events[events.length - 1].at,
    ...t,
    events,
  };
}

